#!/usr/bin/env python3
"""
Writes `crates/zh_ffi/src/engine_sim_generated.rs`: the `SimView`/`SimApi`
implementation that lets a ported module run inside the C++ engine.

Both traits require every method, so an adapter has to name all of them. Methods
listed in `WIRED` forward to a hand-written `EngineSim::engine_<name>` in
`crates/zh_ffi/src/engine_sim.rs`; every other method aborts with its name.

  python3 scripts/gen_engine_sim.py          # rewrite the file
  python3 scripts/gen_engine_sim.py --check  # fail if it is out of date
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
TRAITS_SOURCE = REPO_ROOT / "crates/zh_logic/src/sim/mod.rs"
OUTPUT = REPO_ROOT / "crates/zh_ffi/src/engine_sim_generated.rs"
TRAITS = ("SimView", "SimApi")

# Methods the engine really answers. Add a name here, then write `engine_<name>`.
WIRED = (
    "frame",
    "object_is_kind_of",
    "object_max_health",
    "hulk_max_lifetime_override",
    "rng_logic_int",
    "set_wake_frame",
    "attempt_damage",
)


class GenError(Exception):
    pass


def use_statements(source: str) -> list[str]:
    """The file's top-level `use` items, rewritten for use from outside `zh_logic`."""
    found = re.findall(r"^use [^;]+;", source, flags=re.MULTILINE)
    return [statement.replace("use crate::", "use zh_logic::") for statement in found]


def trait_body(source: str, name: str) -> str:
    """The text between the braces of `pub trait <name>`."""
    match = re.search(rf"^pub trait {name}\b[^\n]*\{{\n(.*?)^\}}", source, re.MULTILINE | re.DOTALL)
    if not match:
        raise GenError(f"trait {name} not found")
    return match.group(1)


def methods(body: str) -> list[tuple[str, str, list[str]]]:
    """(name, signature, argument names) for each method; all must lack a default body."""
    code = "\n".join(line.split("//")[0].rstrip() for line in body.splitlines())
    result = []
    position = 0
    while True:
        start = code.find("fn ", position)
        if start < 0:
            return result
        depth = 0
        end = start
        while end < len(code):
            char = code[end]
            if char in "([":
                depth += 1
            elif char in ")]":
                depth -= 1
            elif depth == 0 and char in ";{":
                break
            end += 1
        if end == len(code):
            raise GenError(f"unterminated signature: {code[start:start + 80]}")
        signature = " ".join(code[start:end].split())
        name = re.match(r"fn (\w+)", signature).group(1)
        if code[end] == "{":
            raise GenError(f"{name} has a default body; teach the generator about it")
        params = signature[signature.index("(") + 1 :]
        args = re.findall(r"(?:^|,)\s*(?:mut )?(\w+)\s*:(?!:)", params)
        result.append((name, signature.replace("crate::", "zh_logic::"), args))
        position = end + 1


def render(source: str, wired: tuple[str, ...] = WIRED) -> str:
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// @generated by scripts/gen_engine_sim.py from crates/zh_logic/src/sim/mod.rs. Do not edit.",
        "#![allow(unused_imports, unused_variables)]",
        "",
        "use crate::engine_sim::{not_wired, EngineSim};",
        "use zh_logic::sim::*;",
        *use_statements(source),
    ]
    seen: set[str] = set()
    for trait in TRAITS:
        lines += ["", f"impl {trait} for EngineSim<'_> {{"]
        for name, signature, args in methods(trait_body(source, trait)):
            seen.add(name)
            if name in wired:
                body = f"self.engine_{name}({', '.join(args)})"
            else:
                body = f'not_wired("{name}")'
            lines += [f"    {signature} {{", f"        {body}", "    }"]
        lines.append("}")
    missing = sorted(set(wired) - seen)
    if missing:
        raise GenError(f"WIRED names no trait declares: {', '.join(missing)}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the engine-backed SimApi.")
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)
    try:
        text = render(TRAITS_SOURCE.read_text())
    except GenError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != text:
            print(f"ERROR: {OUTPUT.name} is out of date; run scripts/gen_engine_sim.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.name} is up to date")
        return 0
    OUTPUT.write_text(text)
    print(OUTPUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
