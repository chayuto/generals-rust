/// The names the engine interns before reading the files of `path`.
pub(crate) fn before_init_path(rules: &mut RulesRegistry, path: &str) {
    match path {
        // `TheFunctionLexicon`, then `TheModuleFactory`.
        "Data\\INI\\Rank" => {
            // `TheNameKeyGenerator->syncNameKeyID`, after `TheAudio`.
            #[cfg(feature = "retail-crc")]
            rules.name_keys.sync_name_key_id();
            intern(&mut rules.name_keys, &FUNCTION_LEXICON_NAMES);
            rules.register_module_factory();
            rules
                .module_registry
                .register_w3d_draw_stubs(&mut rules.name_keys);
        }
        "Data\\INI\\Default\\Upgrade" => rules.upgrade_center.init(&mut rules.name_keys),
        // The end of `TheInGameUI->init`.
        "Data\\INI\\ChallengeMode" => intern(&mut rules.name_keys, &CONTROL_BAR_NAMES),
        // `TheScriptEngine`, in `TheGameLogic->init`.
        "Data\\INI\\Default\\Crate" => {
            script_template_registry(&mut rules.name_keys);
        }
        _ => {}
    }
}

/// The names interned once every file is read: the map cache's first waypoint
/// property and the first window the subsystem reset looks up.
pub(crate) fn after_init_paths(rules: &mut RulesRegistry) {
    intern(
        &mut rules.name_keys,
        &["InitialCameraPosition", "Diplomacy.wnd:ListboxSolo"],
    );
}

/// The names a client block's parser interns. `lines` start at the block header.
pub(crate) fn intern_client_block(
    keys: &mut NameKeyGenerator,
    kind: &str,
    name: &str,
    lines: &[&[u8]],
) {
    match kind {
        "MappedImage" => {
            keys.name_to_lowercase_key(name);
        }
        "ControlBarScheme" => {
            for line in lines.iter().skip(1) {
                let Ok(line) = std::str::from_utf8(line) else {
                    continue;
                };
                let mut words = line
                    .split(';')
                    .next()
                    .unwrap_or("")
                    .split(|c: char| c <= ' ' || c == '=')
                    .filter(|w| !w.is_empty());
                let field = words.next().unwrap_or("");
                if SCHEME_IMAGE_FIELDS
                    .iter()
                    .any(|f| f.eq_ignore_ascii_case(field))
                {
                    if let Some(image) = words.next() {
                        keys.name_to_lowercase_key(image);
                    }
                }
            }
        }
        _ => {}
    }
}

fn intern(keys: &mut NameKeyGenerator, names: &[&str]) {
    for name in names {
        keys.name_to_key(name);
    }
}

